import { chromium } from '@playwright/test';
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 390, height: 844 } });
let errs = [];
page.on('pageerror', (e) => errs.push(String(e).split('\n')[0]));
await page.goto('http://localhost:3131/plans');
await page.waitForTimeout(1500);
await page.locator('.plan-tabs').getByRole('button', { name: '模板' }).click();
await page.waitForTimeout(500);
await page.getByRole('button', { name: '新建模板' }).click();
await page.waitForTimeout(500);
await page.locator('.tpl-form input[type="text"]').first().fill('晨间启动例程');
const ti = page.locator('.tpl-form input[type="text"]');
await ti.nth(1).fill('查看今日计划');
await page.getByPlaceholder('预估/分').fill('5');
await page.getByRole('button', { name: '加一个子任务' }).click();
await ti.nth(2).fill('复盘昨日');
await page.getByPlaceholder('预估/分').nth(1).fill('15');
await page.getByRole('button', { name: '保存模板' }).click();
await page.waitForTimeout(1000);
await page.getByRole('button', { name: '创建本组计划' }).click();
await page.waitForTimeout(1000);
await page.locator('.plan-tabs').getByRole('button', { name: '计划' }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: 'E:/study/zi/MyTime/.tpl-final.png', fullPage: true });
const check = await page.evaluate(async () => {
  const db = window.__mytimeDebug.db;
  const plans = (await db.plans.toArray()).filter((p) => !p.deleted);
  const withTpl = plans.filter((p) => p.templateId && p.instanceId);
  return { withTpl: withTpl.length, groups: new Set(withTpl.map((p) => p.instanceId)).size, titles: withTpl.map((p) => p.title), statuses: withTpl.map((p) => p.status) };
});
console.log('页面错误数:', errs.length, errs[0] || '' , '| DB断言:', JSON.stringify(check));
await b.close();
